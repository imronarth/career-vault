CREATE TABLE user_accounts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    role          VARCHAR(30)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE career_documents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(200) NOT NULL,
    category          VARCHAR(30)  NOT NULL,
    version_label     VARCHAR(50),
    issuer_or_context VARCHAR(200),
    document_date     DATE,
    tags              VARCHAR(500),
    description       TEXT,
    original_filename VARCHAR(255) NOT NULL,
    stored_filename   VARCHAR(255) NOT NULL UNIQUE,
    content_type      VARCHAR(150) NOT NULL,
    file_size_bytes   BIGINT       NOT NULL,
    sha256_checksum   VARCHAR(64)  NOT NULL,
    is_primary        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE job_applications (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name             VARCHAR(200) NOT NULL,
    role_title               VARCHAR(200) NOT NULL,
    job_url                  VARCHAR(2048),
    platform                 VARCHAR(100),
    work_mode                VARCHAR(20)  NOT NULL,
    location                 VARCHAR(200),
    salary_range             VARCHAR(100),
    status                   VARCHAR(30)  NOT NULL,
    applied_date             DATE,
    follow_up_date           DATE,
    contact_person           VARCHAR(200),
    notes                    TEXT,
    cv_document_id           BIGINT REFERENCES career_documents (id) ON DELETE SET NULL,
    cover_letter_document_id BIGINT REFERENCES career_documents (id) ON DELETE SET NULL,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE job_status_history (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_application_id BIGINT      NOT NULL REFERENCES job_applications (id) ON DELETE CASCADE,
    from_status        VARCHAR(30),
    to_status          VARCHAR(30) NOT NULL,
    note               TEXT,
    changed_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_job_applications_status ON job_applications (status);
CREATE INDEX idx_job_applications_applied_date ON job_applications (applied_date DESC);
CREATE INDEX idx_career_documents_category ON career_documents (category);
CREATE INDEX idx_job_status_history_job_application_id ON job_status_history (job_application_id);
